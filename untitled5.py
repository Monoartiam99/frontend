# ------------------------------------------------------------
# 3. WHEEL CREATION
# ------------------------------------------------------------

def create_wheel(
    x,
    y,
    z,
    radius=27,
    width=12,
    segments=64
):

    vertices = []

    faces = []

    # Front and back centers
    vertices.append([
        x,
        y-width/2,
        z
    ])

    vertices.append([
        x,
        y+width/2,
        z
    ])

    front_center = 0
    back_center = 1

    # Ring vertices
    for i in range(segments):

        angle = (
            2*np.pi*i/segments
        )

        xx = x + radius*np.cos(angle)
        zz = z + radius*np.sin(angle)

        vertices.append([
            xx,
            y-width/2,
            zz
        ])

        vertices.append([
            xx,
            y+width/2,
            zz
        ])

    # Faces
    for i in range(segments):

        ni = (i+1) % segments

        f1 = 2 + i*2
        f2 = 2 + ni*2

        b1 = 3 + i*2
        b2 = 3 + ni*2

        # Front
        faces.append([
            front_center,
            f1,
            f2
        ])

        # Back
        faces.append([
            back_center,
            b2,
            b1
        ])

        # Side
        faces.append([
            f1,
            b1,
            b2
        ])

        faces.append([
            f1,
            b2,
            f2
        ])

    return (
        np.array(vertices),
        np.array(faces)
    )


