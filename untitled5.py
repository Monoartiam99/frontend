# ------------------------------------------------------------
# 2. CREATE EXTRUDED BODY
# ------------------------------------------------------------

def create_extruded_polygon(points, depth):

    points = np.asarray(points)

    n = len(points)

    vertices = []

    # Front side
    for x, z in points:
        vertices.append([x, -depth/2, z])

    # Back side
    for x, z in points:
        vertices.append([x, depth/2, z])

    vertices = np.array(vertices)

    faces = []

    # Front face
    for i in range(1, n-1):
        faces.append([
            0,
            i,
            i+1
        ])

    # Back face
    for i in range(1, n-1):
        faces.append([
            n,
            n+i+1,
            n+i
        ])

    # Side walls
    for i in range(n):

        j = (i+1) % n

        faces.append([
            i,
            j,
            n+j
        ])

        faces.append([
            i,
            n+j,
            n+i
        ])

    return vertices, np.array(faces)


