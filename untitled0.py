import cv2
import numpy as np
import matplotlib.pyplot as plt
from PIL import Image
import os

# ------------------------------------------------------------
# 1. INPUT
# ------------------------------------------------------------

input_path = "/content/ResShift/input_image.png"

if not os.path.exists(input_path):
    raise FileNotFoundError(
        f"Image not found: {input_path}\n"
        "Please make sure your ORIGINAL image is copied there."
    )

img = cv2.imread(input_path)

if img is None:
    raise ValueError("Could not read the input image.")

print("Original size:", img.shape[1], "x", img.shape[0])


# ------------------------------------------------------------
# 2. GRAYSCALE
# ------------------------------------------------------------

gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)


# ------------------------------------------------------------
# 3. UPSCALE
#    3x enlargement gives OCR much more pixel information
# ------------------------------------------------------------

scale = 3

up = cv2.resize(
    gray,
    None,
    fx=scale,
    fy=scale,
    interpolation=cv2.INTER_CUBIC
)


# ------------------------------------------------------------
# 4. REMOVE SMALL SCANNER / COMPRESSION NOISE
#    Keep edges and characters intact.
# ------------------------------------------------------------

denoised = cv2.fastNlMeansDenoising(
    up,
    None,
    h=5,
    templateWindowSize=7,
    searchWindowSize=21
)


# ------------------------------------------------------------
# 5. LOCAL CONTRAST ENHANCEMENT
